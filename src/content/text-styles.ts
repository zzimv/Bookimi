function lengthGuide(audiences: AudienceKey[], unit = "слов"): string {
  const rows = SEGMENTS.filter((s) => audiences.includes(s.audience)).map(
    (s) => `— ${s.title} (${s.id}): ${s.text.wordsPerSpread[0]}–${s.text.wordsPerSpread[1]} ${unit} на разворот; ${s.text.sentenceStyle}.`,
  );
  return `ДЛИНА ПО СЕГМЕНТАМ (сегмент указан в брифе)\n${rows.join("\n")}`;
}

