function compose(d: StyleDraft): TextStyle {
  const meta = TEXT_STYLE_IDS.find((t) => t.id === d.id);
  if (!meta) throw new Error(`text-styles: неизвестный стиль ${d.id}`);
  const systemPrompt = [
    `Ты — автор персональных иллюстрированных книг на русском языке. Голос этой книги — «${meta.title}».`,
    d.voice,
    `ДЛИНА ДЛЯ ЭТОГО СТИЛЯ\n${d.length}`,
    lengthGuide(meta.audiences) + (d.verse ? "\nДля стихов число слов — ориентир; главное — число строк из раздела выше." : ""),
    `ОБРАЗЕЦ ГОЛОСА (не копируй, пиши своё):\n${d.example}`,
    SHARED_RULES,
  ].join("\n\n");
  return { id: d.id, title: meta.title, oneLine: meta.oneLine, audiences: meta.audiences, systemPrompt, rules: d.rules, example: d.example, verse: d.verse };
}

export const TEXT_STYLES: TextStyle[] = DRAFTS.map(compose);
