// Модерация текста до отправки в генерацию и до показа клиенту.
// Словарный фильтр (грубая лексика, насилие, ссылки и реклама). Спорные книги оператор
// проверяет и перегенерирует вручную в админке.
// (?<![а-яё]) — начало слова: \b в JS не работает с кириллицей.
const S = "(?<![а-яёa-z])"; // начало слова
const E = "(?![а-яё])"; // конец слова
const BAD = [
  new RegExp(`${S}(х[уy][йяеёи]|п[иi]зд|[её]б[ауоеиыё]т|[её]бан|бля${E}|бляд|сук[аи]${E}|муд[аио]к|гандон|шлюх)`, "i"),
  new RegExp(`${S}(убить|убей|убийств|насил|самоубий|суицид|наркот)`, "i"),
  /(https?:\/\/|www\.|t\.me\/|@[a-z0-9_]{4,})/i,
];

export function checkText(text: string): string | null {
  for (const re of BAD) if (re.test(text)) return "недопустимое содержание";
  return null;
}

/** Проверка свободных полей анкеты: имя, посвящение, своя идея. */
export function checkInputs(fields: string[]) {
  return checkText(fields.filter(Boolean).join("\n"));
}
