/** Те же основы, что speciesOf в art/pets.ts, но по границе слова: «особый» — не собака, «который» — не кот. */
const CAT_RE = /(?<![а-яa-z])(кот(?!ор)|кош|кис[аеуыо]?(?![а-я])|кисул|киск|котик|котен|котён|мурк|kitten|kitty|cat)/i;
const DOG_RE = /(?<![а-яa-z])(п[её]с(?![а-я])|пес(ик|ель)|псин|собак|собач|щен|doggy|dog|puppy)/i;

/** Вид по свободному тексту: «рыжий кот» → cat, «щенок корги» → dog; не понять — null. */
export function speciesFromText(text: string | undefined | null): "cat" | "dog" | null {
  const s = (text ?? "").toLowerCase();
  if (!s) return null;
  const cat = CAT_RE.exec(s);
  const dog = DOG_RE.exec(s);
  if (cat && dog) return cat.index <= dog.index ? "cat" : "dog";
  return cat ? "cat" : dog ? "dog" : null;
}

/**
 * Вид питомца — доп. героя: выбор в анкете (Кошка / Собака / Другое) → описание и «кто это» → кличка
 * («Котик», «Кисуля»). Не понять — null (рисовальщик возьмёт собаку по умолчанию, текст — нейтральный «питомец»).
 */
export function extraSpecies(e: ExtraIn): "cat" | "dog" | "other" | null {
  if (e.role !== "pet") return null;
  if (e.species) return e.species;
  return speciesFromText(`${e.what ?? ""} ${e.description ?? ""}`) ?? speciesFromText(e.name);
}

