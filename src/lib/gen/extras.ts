export type ExtraKind = "parent" | "kid" | "cat" | "dog" | "pet" | "thing";

export function extraKind(e: ExtraIn): ExtraKind {
  switch (e.role) {
    case "mom":
    case "dad":
    case "grandma":
    case "grandpa":
    case "owner":
    case "colleague":
      return "parent";
    case "pet": {
      const sp = extraSpecies(e);
      return sp === "cat" ? "cat" : sp === "dog" ? "dog" : "pet";
    }
    case "toy":
    case "custom":
      return "thing";
    default:
      return "kid";
  }
}

const ROLE_WORD: Record<string, [string, string]> = {
  mom: ["мама", "мама"],
  dad: ["папа", "папа"],
  grandma: ["бабушка", "бабушка"],
  grandpa: ["дедушка", "дедушка"],
  sibling: ["брат", "сестра"],
  friend: ["друг", "подружка"],
};

/** Слово перед именем: «мама», «сестра», «кошка», «плюшевый заяц», «дерево»; пусто — только имя. */
export function extraWord(e: ExtraIn): string {
  const g = extraGender(e, guessGender);
  const fem = g === "girl";
  let w = "";
  if (ROLE_WORD[e.role]) w = ROLE_WORD[e.role][fem ? 1 : 0];
  else if (e.role === "pet") {
    const sp = extraSpecies(e);
    w = sp === "cat" ? (fem ? "кошка" : "кот") : sp === "dog" ? (fem ? "собака" : "пёс") : (e.what ?? "").trim().toLowerCase();
  } else if (e.role === "toy" || e.role === "custom") w = (e.what ?? "").trim().toLowerCase();
  if (!w) return "";
  // «Мама Оля» в имени, «Робот Бип» при «что это: робот» — второй раз слово не пишем
  const name = e.name.trim().toLowerCase().replace(/ё/g, "е");
  const word = w.replace(/ё/g, "е");
  if (name === word || name.startsWith(word + " ") || name.startsWith(word.split(/\s+/).at(-1)! + " ")) return "";
  return w;
}

