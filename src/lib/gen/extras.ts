/** Что передать рисовальщику питомца: вид, порода и окрас — из описания («рыжий кот с белыми лапками»). */
export function extraPetLook(e: ExtraIn): { species?: string; breed?: string; furColor?: string } {
  if (e.role !== "pet") return {};
  const sp = extraSpecies(e);
  const desc = [e.what, e.description].filter(Boolean).join(", ");
  // «Другое»: вид словами (хомяк, попугай, кролик) — рисовальщик выберет свой рисунок; иначе — милый зверёк
  const species = sp === "other" ? desc || "other" : sp ?? undefined;
  return { species, breed: desc || undefined, furColor: e.description || undefined };
}

/** Предмет для «своего варианта» и игрушки: «плюшевый заяц», «дерево», иначе имя. */
export function extraThing(e: ExtraIn): string | undefined {
  if (e.role !== "toy" && e.role !== "custom") return e.what || undefined;
  return e.what || (e.role === "toy" ? [e.description, e.name].filter(Boolean).join(" ") : e.name) || undefined;
}

