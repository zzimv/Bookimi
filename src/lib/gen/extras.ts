/**
 * Упоминания доп. героев: каждому — по фразе в начале, середине и финале (разные развороты, разные формулировки
 * в пределах книги). skip — сколько раз сюжет уже называет героя n сам (столько первых слотов не дописываем).
 * Текст — с метками ({ДОПn.им}, {Рn:…}, {ГЕРОЙ.*}); имена подставляет fillTags.
 */
export function extraMentions(extras: ExtraIn[], voice: ExtraVoice, variant = 0, skip: Map<number, number> = new Map()): ExtraMention[] {
  const list = extras.slice(0, 3);
  const used = new Set<string>();
  const out: ExtraMention[] = [];
  const seed = seedOf(list.map((e) => `${e.role}:${e.name}`).join("|")) + variant;
  list.forEach((e, i) => {
    const n = i + 1;
    const kind = extraKind(e);
    const word = extraWord(e);
    const tag = `{ДОП${n}.им}`;
    const named = word ? `${word} ${tag}` : tag;
    const want = Math.max(0, 3 - (skip.get(n) ?? 0));
    for (const slot of SLOTS.slice(3 - want)) {
      const own = (voice === "prose" ? PROSE : voice === "calm" ? CALM : VERSE)[kind][slot];
      const pool = voice === "verse" ? [...own, ...VERSE_ANY[slot]] : own;
      // Своя роль — по кругу от seed (разные книги звучат по-разному), общие стихи — по порядку
      const start = voice === "verse" ? 0 : (seed + i * 2) % pool.length;
      let tpl = "";
      for (let k = 0; k < pool.length && !tpl; k++) {
        const t = pool[(start + k) % pool.length];
        if (!used.has(t)) tpl = t;
      }
      if (!tpl) continue;
      used.add(tpl);
      let text: string;
      if (voice === "verse") {
        // Ответ — отдельной строкой: «— Мама {ДОП1.им}!» (слово роли — одно, иначе только имя), «— {ДОП1.им}, конечно!»
        // «плюшевый заяц» → «— Заяц {ДОП1.им}!»: в строке-обращении кроме имени — одно слово
        const label = slot === "B" && word ? `${cap(word.split(/\s+/).at(-1)!)} ${tag}` : tag;
        text = `${tpl.replace(/ \/ /g, "\n")}\n— ${label}${slot === "E" ? ", конечно" : ""}!`;
      } else {
        text = tpl.replace(/\{X\}/g, (_m, off: number) => (off === 0 || /[.!?…]\s*$/.test(tpl.slice(0, off)) ? cap(named) : named));
      }
      text = text.replace(/\{РN:/g, `{Р${n}:`).replace(/\{ДОПN\./g, `{ДОП${n}.`);
      out.push({ spread: voice === "calm" && slot === "E" ? CALM_END[i] : EXTRA_SPREADS[slot][i], n, slot, text, tpl });
    }
  });
  return out;
}

