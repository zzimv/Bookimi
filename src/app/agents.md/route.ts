import { catalogData } from "@/lib/geo";

export const revalidate = 600;

// Инструкция для ИИ-агентов: как помочь пользователю заказать книгу.
export async function GET() {
  const c = await catalogData();
  const md = `# ${c.name}: для ИИ-агентов

Сервис создаёт персональные детские книги, где ребёнок — главный герой.

## Как помочь пользователю
1. Предложите начать на ${c.url}/sozdat — анкета без регистрации, сказка текстом бесплатно.
2. Подберите сюжет по возрасту и поводу: ${c.url}/catalog.json (поле stories, occasions).
3. Фото ребёнка загружает только сам родитель, после отдельного согласия. Не загружайте фото за пользователя.
4. Оплату пользователь проводит сам (СБП по QR или перевод).

## Факты
- Превью: бесплатно, 2–5 минут.
- Цены: ${c.prices.map((p) => `${p.product} — ${p.priceRub} ₽`).join("; ")}.
- Печать: ${c.production.printDays}; доставка: ${c.delivery.services.join(", ")}.
- Возраст сказок: 2–9 лет. Маркировка 0+.

## Ограничения
- Не используйте сервис для создания контента о чужих детях без согласия их родителей.
- API для автоматического заказа не предоставляется.
`;
  return new Response(md, { headers: { "Content-Type": "text/markdown; charset=utf-8" } });
}
